#!/usr/bin/env bash
# One-time setup, and the way to rebuild the containers after a dependency changed: checks Docker,
# builds the images, creates secrets/secrets.yaml from its template if it does not exist yet (with
# a generated session_secret) and names the values that are still to fill in.
source "$(dirname "${BASH_SOURCE[0]}")/helpers/common.sh"
source "$REPO_ROOT/scripts/helpers/preflight.sh"

preflight_setup

info "Building the containers ..."
compose build

SECRETS_FILE="$REPO_ROOT/secrets/secrets.yaml"
if [[ -f "$SECRETS_FILE" ]]; then
  success "secrets/secrets.yaml exists and is kept as it is"
else
  # Created on the host, so it belongs to the developer, who edits it next. Never overwritten.
  cp "$REPO_ROOT/secrets/secrets.example.yaml" "$SECRETS_FILE"
  printf '# Signs the session cookie. Generated by setup.sh.\nsession_secret: "%s"\n' \
    "$(openssl rand -hex 32)" >> "$SECRETS_FILE"
  success "Created secrets/secrets.yaml with a generated session_secret"
fi

if check_secrets_complete; then
  success "Setup is done. Next: ./scripts/start.sh"
else
  info "Setup is done once these values are filled in. Next: ./scripts/start.sh"
fi
